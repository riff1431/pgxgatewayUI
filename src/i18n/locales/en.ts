type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStringify<T[K]>
}

export type TranslationSchema = DeepStringify<typeof en>

type DotPrefix<T extends string, P extends string> = P extends '' ? T : `${P}.${T}`

type ExtractDotPaths<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string
    ? DotPrefix<K, Prefix>
    : ExtractDotPaths<T[K], DotPrefix<K, Prefix>>
}[keyof T & string]

export type TranslationKey = ExtractDotPaths<typeof en>
